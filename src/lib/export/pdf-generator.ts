import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

interface PDFOptions {
  tenantName: string;
  logoUrl?: string;
  primaryColor: string;
  secondaryColor: string;
  examTitle: string;
  examDate: Date | string | null;
  rows: any[];
  totalMarks: number;
  passingPercentage: number;
  showPoweredBy: boolean;
}

interface StudentResultPDFOptions {
  tenantName: string;
  logoUrl?: string;
  primaryColor: string;
  examTitle: string;
  examDate: Date | string | null;
  studentName: string;
  rollNumber: string;
  score: number;
  totalMarks: number;
  percentage: number;
  passingPercentage: number;
  passed: boolean;
  correct: number;
  wrong: number;
  unattempted: number;
  answers: any[];
}

function formatDate(dateInput: Date | string | null | undefined): string {
  if (!dateInput) return new Date().toLocaleDateString('en-IN');
  const d = dateInput instanceof Date ? dateInput : new Date(dateInput);
  return !isNaN(d.getTime()) ? d.toLocaleDateString('en-IN') : new Date().toLocaleDateString('en-IN');
}

export async function loadImageAsBase64(url: string): Promise<string | null> {
  if (!url) return null;
  if (url.startsWith('data:')) return url;
  
  try {
    const port = process.env.PORT || 3000;
    const fullUrl = url.startsWith('/') ? `http://localhost:${port}${url}` : url;
    const response = await fetch(fullUrl);
    if (!response.ok) return null;
    const buffer = await response.arrayBuffer();
    const base64 = Buffer.from(buffer).toString('base64');
    const contentType = response.headers.get('content-type') || 'image/png';
    return `data:${contentType};base64,${base64}`;
  } catch {
    return null;
  }
}

export async function generateStudentResultPDF(options: StudentResultPDFOptions): Promise<jsPDF> {
  const doc = new jsPDF('portrait', 'mm', 'a4');
  const pageWidth = 210;
  const pageHeight = 297;
  
  const primaryColor = options.primaryColor || '#2563EB';
  let yPos = 15;
  
  // ===== HEADER =====
  if (options.logoUrl) {
    try {
      const imgData = await loadImageAsBase64(options.logoUrl);
      if (imgData) doc.addImage(imgData, 'PNG', 15, yPos, 30, 15);
    } catch (e) {}
  }
  
  doc.setFontSize(22);
  doc.setTextColor(primaryColor);
  doc.setFont('helvetica', 'bold');
  doc.text(options.tenantName || 'Institution', pageWidth / 2, yPos + 10, { align: 'center' });
  
  yPos += 25;
  doc.setDrawColor(primaryColor);
  doc.setLineWidth(0.5);
  doc.line(15, yPos, pageWidth - 15, yPos);
  yPos += 10;
  
  // ===== EXAM & STUDENT DETAILS =====
  doc.setFontSize(16);
  doc.setTextColor('#1e293b');
  doc.setFont('helvetica', 'bold');
  doc.text('EXAM RESULT REPORT', pageWidth / 2, yPos, { align: 'center' });
  
  yPos += 15;
  doc.setFontSize(11);
  doc.setTextColor('#334155');
  doc.text(`Exam Name: ${options.examTitle || 'N/A'}`, 15, yPos);
  doc.text(`Date: ${formatDate(options.examDate)}`, pageWidth - 15, yPos, { align: 'right' });
  
  yPos += 8;
  doc.text(`Student Name: ${options.studentName || 'N/A'}`, 15, yPos);
  doc.text(`Roll Number: ${options.rollNumber || 'N/A'}`, pageWidth - 15, yPos, { align: 'right' });
  
  yPos += 15;
  
  // ===== SUMMARY BOX =====
  doc.setFillColor('#f8fafc');
  doc.setDrawColor('#e2e8f0');
  doc.rect(15, yPos, pageWidth - 30, 35, 'FD');
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor('#0f172a');
  doc.text('Performance Summary', 20, yPos + 8);
  
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Total Score: ${options.score} / ${options.totalMarks}`, 20, yPos + 18);
  doc.text(`Percentage: ${Number(options.percentage || 0).toFixed(1)}%`, 20, yPos + 26);
  
  doc.text(`Correct: ${options.correct || 0}`, pageWidth / 2 - 10, yPos + 18);
  doc.text(`Wrong: ${options.wrong || 0}`, pageWidth / 2 - 10, yPos + 26);
  
  const statusColor = options.passed ? '#16a34a' : '#dc2626';
  doc.setTextColor(statusColor);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(options.passed ? 'PASSED' : 'FAILED', pageWidth - 20, yPos + 22, { align: 'right' });
  
  yPos += 50;
  
  // ===== FOOTER =====
  doc.setFontSize(8);
  doc.setTextColor('#94a3b8');
  doc.setFont('helvetica', 'italic');
  doc.text('Generated by TrinetraEdu-AI', pageWidth / 2, pageHeight - 10, { align: 'center' });
  
  return doc;
}

export async function generateResultsPDF(options: PDFOptions): Promise<jsPDF> {
  const doc = new jsPDF('landscape', 'mm', 'a4');
  const pageWidth = 297;
  const pageHeight = 210;
  const primaryColor = options.primaryColor || '#2563EB';
  
  let yPos = 10;
  if (options.logoUrl) {
    try {
      const imgData = await loadImageAsBase64(options.logoUrl);
      if (imgData) doc.addImage(imgData, 'PNG', 14, yPos, 30, 15);
    } catch (e) {}
  }
  
  doc.setFontSize(18);
  doc.setTextColor(primaryColor);
  doc.setFont('helvetica', 'bold');
  doc.text(options.tenantName || 'Institution', pageWidth / 2, yPos + 8, { align: 'center' });
  
  doc.setFontSize(14);
  doc.setTextColor('#1e293b');
  doc.text(options.examTitle || 'Exam Results', pageWidth / 2, yPos + 18, { align: 'center' });
  
  doc.setFontSize(10);
  doc.setTextColor('#64748b');
  doc.setFont('helvetica', 'normal');
  doc.text(`Date: ${formatDate(options.examDate)}`, pageWidth / 2, yPos + 24, { align: 'center' });
  
  doc.setDrawColor(primaryColor);
  doc.setLineWidth(0.5);
  doc.line(14, yPos + 28, pageWidth - 14, yPos + 28);
  
  const columns = [
    { header: 'Name', dataKey: 'name' },
    { header: 'Roll No', dataKey: 'rollNo' },
    { header: 'Email', dataKey: 'email' },
    { header: 'Branch', dataKey: 'branch' },
    { header: 'Section', dataKey: 'section' },
    { header: 'Total Que', dataKey: 'totalQue' },
    { header: 'Correct', dataKey: 'correct' },
    { header: 'Wrong', dataKey: 'wrong' },
    { header: 'Unattempt', dataKey: 'unattempt' },
    { header: 'Percentage', dataKey: 'percentage' },
    { header: 'Score', dataKey: 'score' },
    { header: 'Rank', dataKey: 'rank' },
  ];
  
  autoTable(doc, {
    startY: yPos + 32,
    head: [columns.map(c => c.header)],
    body: (options.rows || []).map(row => [
      row.name || 'N/A', row.rollNo || 'N/A', row.email || 'N/A', row.branch || 'N/A', row.section || 'N/A',
      row.totalQue || 0, row.correct || 0, row.wrong || 0, row.unattempt || 0,
      `${Number(row.percentage || 0).toFixed(1)}%`, row.score || 0, row.rank || 1,
    ]),
    theme: 'striped',
    headStyles: { fillColor: primaryColor, textColor: '#ffffff', fontSize: 9, fontStyle: 'bold' },
    bodyStyles: { fontSize: 8 },
    margin: { left: 14, right: 14 },
    didDrawPage: function () {
      if (options.showPoweredBy !== false) {
        doc.setFontSize(6);
        doc.setTextColor('#94a3b8');
        doc.setFont('helvetica', 'italic');
        doc.text('Powered by TrinetraEdu-AI', pageWidth - 14, pageHeight - 8, { align: 'right' });
      }
    },
  });
  
  const finalY = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 10 : yPos + 40;
  const totalStudents = options.rows ? options.rows.length : 0;
  const passed = options.rows ? options.rows.filter(r => Number(r.percentage || 0) >= (options.passingPercentage || 40)).length : 0;
  const passRate = totalStudents > 0 ? (passed / totalStudents) * 100 : 0;
  
  if (finalY + 30 < pageHeight) {
    doc.setFontSize(9);
    doc.setTextColor('#1e293b');
    doc.setFont('helvetica', 'bold');
    doc.text('Summary:', 14, finalY);
    
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.text(`Total Students: ${totalStudents}`, 14, finalY + 6);
    doc.text(`Passed: ${passed}`, 14, finalY + 12);
    doc.text(`Pass Rate: ${passRate.toFixed(1)}%`, 14, finalY + 18);
    doc.text(`Total Marks: ${options.totalMarks || 0}`, 14, finalY + 24);
  }
  
  return doc;
}
